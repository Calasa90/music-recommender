-- 1. Resumen de coincidencias por track_id
SELECT
    COUNT(*) AS enlaces_recibidos,
    COUNT(DISTINCT t.track_id) AS track_ids_distintos,
    COUNT(s.song_id) AS coincidencias_exactas,
    SUM(CASE WHEN s.song_id IS NULL THEN 1 ELSE 0 END) AS sin_coincidencia,
    SUM(CASE WHEN s.song_id IS NOT NULL
              AND s.energy IS NOT NULL
              AND s.danceability IS NOT NULL
              AND s.valence IS NOT NULL
              AND s.tempo IS NOT NULL
             THEN 1 ELSE 0 END) AS coincidencias_con_4_metricas
FROM tmp_rock_classics AS t
LEFT JOIN songs AS s ON s.track_id = t.track_id;

-- 2. Canciones encontradas, con su posicion original y metricas
SELECT
    t.position, s.track_id, s.track_name, s.album_name,
    GROUP_CONCAT(DISTINCT a.artist_name ORDER BY a.artist_name SEPARATOR ', ') AS artists,
    s.energy, s.danceability, s.valence, s.tempo
FROM tmp_rock_classics AS t
JOIN songs AS s ON s.track_id = t.track_id
LEFT JOIN performs AS pf ON pf.song_id = s.song_id
LEFT JOIN artists AS a ON a.artist_id = pf.artist_id
GROUP BY t.position, s.track_id, s.track_name, s.album_name,
         s.energy, s.danceability, s.valence, s.tempo
ORDER BY t.position;

-- 3. Primeras 30 canciones sin coincidencia exacta
SELECT t.position, t.track_id
FROM tmp_rock_classics AS t
LEFT JOIN songs AS s ON s.track_id = t.track_id
WHERE s.song_id IS NULL
ORDER BY t.position
LIMIT 30;

